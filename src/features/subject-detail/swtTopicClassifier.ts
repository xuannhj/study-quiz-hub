export function classifySwtQuestion(q: Question): SwtTopic {
  const text = (
    q.prompt +
    ' ' +
    q.options.map((o) => o.text).join(' ') +
    ' ' +
    (q.explanation || '')
  ).toLowerCase();

  let bestTopic: SwtTopic | null = null;
  let maxScore = 0;

  for (const topic of SWT_TOPICS) {
    let score = 0;
    for (const kw of topic.keywords) {
      if (text.includes(kw)) {
        score += 1;
      }
    }
    if (score > maxScore) {
      maxScore = score;
      bestTopic = topic;
    }
  }

  return bestTopic && maxScore > 0 ? bestTopic : OTHER_TOPIC;
}
